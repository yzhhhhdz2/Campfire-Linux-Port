#!/usr/bin/env bash
# Campfire Linux port — 修改自 Xocio/Campfire v1.1.32 (GPL-3.0)。
# 新增：用户级安装脚本。只写 $HOME，不需要 sudo；Bazzite / Silverblue 这类
# 不可变系统可直接用。卸载用同目录的 uninstall.sh。
set -euo pipefail

HERE="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
PREFIX="${PREFIX:-${XDG_DATA_HOME:-$HOME/.local}}"
APP_ID="${APP_ID:-io.github.campfire.Campfire}"
PAYLOAD="$HERE/payload"

if [ ! -f "$PAYLOAD/Campfire.Avalonia" ]; then
    echo "Campfire: 找不到 payload/Campfire.Avalonia，安装包可能不完整。" >&2
    exit 1
fi

LIB="$PREFIX/lib/campfire"
BIN="$PREFIX/bin"
APPS="$PREFIX/share/applications"
ICONS="$PREFIX/share/icons/hicolor/256x256/apps"
META="$PREFIX/share/metainfo"

mkdir -p "$LIB" "$BIN" "$APPS" "$ICONS" "$META"
cp -a "$PAYLOAD/." "$LIB/"

# Windows 侧交叉编译不带 Unix 执行位，这里统一补齐。
chmod 0755 "$LIB/Campfire.Avalonia"
find "$LIB" -name '*.so' -exec chmod 0755 {} \; 2>/dev/null || true

cat > "$BIN/campfire" <<EOF
#!/usr/bin/env bash
# Generated by Campfire install.sh — safe to delete on uninstall.
set -euo pipefail
HERE="\$(cd "\$(dirname "\$(readlink -f "\$0")")" && pwd)"
LIB="\$HERE/../lib/campfire"
export CAMPFIRE_DATA_DIR="\${CAMPFIRE_DATA_DIR:-\${XDG_DATA_HOME:-\$HOME/.local/share}/campfire}"
mkdir -p "\$CAMPFIRE_DATA_DIR"
export LD_LIBRARY_PATH="\$LIB\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
for zip in "\$LIB"/easytier-linux-*.zip; do
    if [ -f "\$zip" ]; then
        export CAMPFIRE_EASYTIER_ZIP="\$zip"
        break
    fi
done
exec "\$LIB/Campfire.Avalonia" "\$@"
EOF
chmod 0755 "$BIN/campfire"

cp "$HERE/assets/campfire.png" "$ICONS/$APP_ID.png"

sed -e "s|@EXEC@|$BIN/campfire|g" \
    -e "s|@ICON@|$APP_ID|g" \
    "$HERE/assets/campfire.desktop.in" > "$APPS/$APP_ID.desktop"

if [ -f "$HERE/assets/campfire.metainfo.xml" ]; then
    cp "$HERE/assets/campfire.metainfo.xml" "$META/$APP_ID.metainfo.xml"
fi

# 桌面数据库 / 图标缓存是尽力而为：不可变系统上通常没有这些命令。
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$APPS" 2>/dev/null || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -f -t "$PREFIX/share/icons/hicolor" 2>/dev/null || true
fi

echo ""
echo "==== Campfire 安装完成 ===="
echo "  程序目录 : $LIB"
echo "  启动命令 : $BIN/campfire"
echo "  桌面入口 : $APPS/$APP_ID.desktop"
echo "  数据目录 : ${XDG_DATA_HOME:-$HOME/.local/share}/campfire（设置、日志、EasyTier）"
echo ""
if [ -d "$BIN" ]; then
    case ":$PATH:" in
        *":$BIN:"*) ;;
        *) echo "  提示：$BIN 不在 PATH 里。可加到 ~/.bashrc："
           echo "        export PATH=\"$HOME/.local/bin:\$PATH\"" ;;
    esac
fi
echo "  卸载：bash $HERE/uninstall.sh"
echo ""
echo "  Minecraft 客户端与 JDK 不含在本安装包内，需另行安装。"
echo "  首次联机会自动准备 EasyTier 组件（离线包已内置则可完全离线）。"
echo ""
